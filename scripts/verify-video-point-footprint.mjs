import assert from 'node:assert/strict';
import { register } from 'node:module';
import * as THREE from 'three';
register('./ts-extension-loader.mjs', import.meta.url);
const { createPointCloudMaterial } = await import('../src/shaders/pointCloudMaterial.ts');
const { POINTS_WORLD_HEIGHT, POSITION_TEXTURE_SIZE } = await import('../src/engine/buffers.ts');
const material = createPointCloudMaterial();
assert.equal(material.uniforms.uVideoFootprint.value, 0, 'photos retain existing sprite sizing');
assert.equal(material.uniforms.uVideoWorldStep.value, POINTS_WORLD_HEIGHT / POSITION_TEXTURE_SIZE);
assert.equal(material.blending, THREE.AdditiveBlending);
assert.equal(material.depthWrite, false);
assert.match(material.vertexShader, /float videoSize = uPointSize \* jitter \* uVideoWorldStep \* projectionMatrix\[1\]\[1\]\s*\* 0\.5 \* uViewportHeightPx \/ max\(-mv\.z, 0\.1\);/);
assert.match(material.vertexShader, /float legacySize = uPointSize \* jitter \* uDprScale \/ max\(-mv\.z, 0\.1\);/);
assert.match(material.vertexShader, /mix\(legacySize, videoSize, step\(0\.5, uVideoFootprint\)\)/);
assert.doesNotMatch(material.fragmentShader, /VIDEO_ALPHA_CUTOFF|alpha = 1\.0;/);
assert.match(material.fragmentShader, /alpha \*= vOpacity;/);
const size = (height, distance) => 6 * (2 / 384) * Math.sqrt(3) * 0.5 * height / Math.max(distance, 0.1);
assert.ok(size(720, 3.5) > 5 && size(720, 3.5) < 6);
assert.equal(size(1440, 3.5), 2 * size(720, 3.5));
assert.equal(size(720, 1.75), 2 * size(720, 3.5));
// Other renderer modes retain their adaptive-DPR sizing contract.
const { createNeonWireMaterial } = await import('../src/shaders/neonWireMaterial.ts');
globalThis.document = { createElement: () => ({ getContext: () => ({ fillRect() {}, fillText() {} }) }) };
const { createAsciiMaterial } = await import('../src/shaders/asciiMaterial.ts');
const ascii = createAsciiMaterial();
assert.equal(ascii.uniforms.uDprScale.value, 1);
assert.match(ascii.vertexShader, /gl_PointSize = uPointSize \* jitter \* uDprScale \/ max\(-mv\.z, 0\.1\);/);
ascii.dispose();
const neon = createNeonWireMaterial();
assert.equal(neon.uniforms.uDprScale.value, 1);
assert.match(neon.vertexShader, /gl_PointSize = max\(uPointSize \* spriteScale \* uDprScale \/ max\(-mv\.z, 0\.1\), 1\.5\);/);
neon.dispose();
material.dispose();
console.log('OK video reference footprint, soft additive sprites and unchanged photo sizing');
