// A stale crop factor after a source/toggle change would alter uncropped neon.
// Exercise the actual Engine crop and uniform dispatch, with GPU transport stubbed.
import assert from 'node:assert/strict';
import { register } from 'node:module';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
register('./ts-extension-loader.mjs', import.meta.url);
const { Engine } = await import('../src/engine/Engine.ts');
const { createNeonWireMaterial } = await import('../src/shaders/neonWireMaterial.ts');
const { createHomeTexture } = await import('../src/engine/buffers.ts');
const material = createNeonWireMaterial();
assert.equal(material.uniforms.uCropDensity?.value, 1, 'uncropped neon must start with identity crop compensation');
const engine = Object.create(Engine.prototype);
Object.assign(engine, {
  homeTexture: createHomeTexture(), currentDepthTexture: null, videoTexture: null,
  photoData: null, objectSeparation: true, renderModes: new Map([['neon', {material}]]),
  pointsMaterial: material, seeded: false, dynamicHome: false,
  currentDpr: 1, initialDpr: 1, useTextureColor: true,
  simulation: { seedFrom() {}, setHome() {} }, refreshGaussians() {},
});
const w=20,h=20,depth=new Float32Array(w*h).fill(.7),mask=new Float32Array(w*h);
for(let y=6;y<14;y++)for(let x=6;x<14;x++)mask[y*w+x]=1;
engine.setDepth(depth,w,h,mask,w,h);
// 8x8 subject plus rounded 12% margin: 10x10 crop from 20x20 = 4x density.
assert.equal(material.uniforms.uCropDensity.value, 4, 'real cropped grid must publish its area-density factor');
assert.equal(material.uniforms.uEdgeThreshold.value,.1,'crop must not overwrite the user threshold');
const late=createNeonWireMaterial();engine.pushSharedUniforms(late);
assert.equal(late.uniforms.uCropDensity.value,4,'switching into neon after crop must inherit compensation');
engine.setObjectSeparation(false);
assert.equal(material.uniforms.uCropDensity.value,1,'turning separation off must immediately restore identity');
engine.setDepth(depth,w,h,mask,w,h);
assert.equal(material.uniforms.uCropDensity.value,1,'uncropped masked photo must keep identity');
engine.setObjectSeparation(true);engine.setDepth(depth,w,h);
assert.equal(material.uniforms.uCropDensity.value,1,'missing mask must not enable compensation');
engine.setDepth(depth,w,h,new Float32Array(w*h).fill(1),w,h);
assert.equal(material.uniforms.uCropDensity.value,1,'full-frame mask must not enable compensation');
engine.setDepth(depth,w,h,mask,w,h);
engine.videoTexture={};engine.camera={fov:60,aspect:1};engine.renderModeName='neon';
engine.pushSharedUniformsAll();
assert.equal(material.uniforms.uCropDensity.value,1,'photo to video/live must disable compensation before the first depth frame');
engine.setDepth(depth,w,h,mask,w,h);
assert.equal(material.uniforms.uCropDensity.value,1,'video/live segmentation must never compensate');
material.dispose();late.dispose();engine.homeTexture.dispose();engine.currentDepthTexture.dispose();
console.log('neon crop verified: actual crop density, untouched user threshold, off/no-mask/full-mask, late mode, video/live identity');

// Optional GPU acceptance evidence, generated by the real-browser fixture.
// PNG equality is stronger than a metric comparison: every encoded pixel
// must match, including the dark background and the soft line endpoints.
const frames=process.argv.indexOf('--frames');
if(frames>=0){
  const root=resolve(process.argv[frames+1]);
  for(const key of ['thumbnail','ozum'])for(const mode of ['full','photo','video','live']){
    assert.deepEqual(readFileSync(resolve(root,`task3-after-${key}-${mode}-10.png`)),
      readFileSync(resolve(root,`task3-before-${key}-${mode}-10.png`)),`${key} ${mode}: uncropped GPU output must be bit-identical`);
  }
  const before=JSON.parse(readFileSync(resolve(root,'task3-before-metrics.json')));
  const after=JSON.parse(readFileSync(resolve(root,'task3-after-metrics.json')));
  for(const a of after.filter(x=>x.crop)){
    const b=before.find(x=>x.key===a.key&&x.crop);
    assert.ok(a.coverage<b.coverage*.85,`${a.key}: crop interior coverage must drop at least 15%`);
    assert.ok(a.saturation>=b.saturation-.01,`${a.key}: preserve subject saturation`);
    assert.ok(a.clippedPct<b.clippedPct,`${a.key}: crop must reduce clipping`);
  }
  console.log('neon GPU evidence verified: 8 bit-identical uncropped photo/video/live frames; crop coverage, saturation and clipping pass on both photos');
}
