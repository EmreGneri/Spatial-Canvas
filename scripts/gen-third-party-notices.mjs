// Generates public/THIRD_PARTY_NOTICES.txt from package-lock.json so it
// cannot rot: `npm run build` runs this before `vite build`, which copies
// public/ verbatim into dist/. Vendored code and model weights are hardcoded
// below (their licenses were verified by hand against the upstream repo /
// Hugging Face model card, cited inline) because they are not npm packages
// and don't appear in package-lock.json.
//   node scripts/gen-third-party-notices.mjs
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const lock = JSON.parse(readFileSync('package-lock.json', 'utf8'));

// Prod dependencies only: package-lock marks a package `dev: true` only when
// it is reachable exclusively through a devDependency path. `@types/*`
// packages contain nothing but .d.ts declarations -- erased by tsc, no
// runtime code ever reaches the bundle -- so they're excluded even though
// some are reachable via a prod path (e.g. a library re-exporting its own
// type deps).
const LICENSE_FILE_NAMES = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'License', 'license'];

function findLicenseFile(dir) {
  if (!existsSync(dir)) return null;
  const entries = readdirSync(dir);
  const match = LICENSE_FILE_NAMES.find((n) => entries.includes(n));
  return match ? join(dir, match) : null;
}

// Pulls just the copyright line(s) out of a LICENSE file rather than
// reproducing the whole (often boilerplate MIT/BSD/ISC) text for every one
// of ~90 packages -- real text either way, just not the full license body.
function copyrightNotice(licensePath) {
  const text = readFileSync(licensePath, 'utf8');
  const lines = text.split(/\r?\n/);
  // Match only a line that IS a copyright statement (starts with the word),
  // not Apache-2.0's boilerplate "Licensor shall mean the copyright owner..."
  // definition, which contains the word but names no one.
  const start = lines.findIndex((l) => /^copyright\b/i.test(l.trim()));
  if (start === -1) return null;
  const out = [];
  for (let i = start; i < lines.length && out.length < 5; i++) {
    if (out.length && lines[i].trim() === '') break;
    out.push(lines[i].trim());
  }
  return out.join('\n  ');
}

const packages = [];
for (const [path, info] of Object.entries(lock.packages)) {
  if (!path) continue; // the root package itself
  if (info.dev) continue;
  const name = path.split('node_modules/').pop();
  if (name.startsWith('@types/')) continue;
  const license = findLicenseFile(path);
  const notice = license && copyrightNotice(license);
  packages.push({ name, version: info.version, license: info.license || '(unlisted)', notice });
}
packages.sort((a, b) => a.name.localeCompare(b.name));

